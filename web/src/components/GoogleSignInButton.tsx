import { Button } from "@tezzeract/ui";

/**
 * Starts server-mediated Google OAuth. Full navigation keeps the OIDC
 * interaction cookie on this origin; React Router would not reach /api.
 */
export function GoogleSignInButton({ disabled = false }: { disabled?: boolean }): JSX.Element {
  return (
    <Button
      type="button"
      variant="outline"
      className="w-full gap-2"
      disabled={disabled}
      onClick={() => {
        window.location.assign("/api/oauth/google");
      }}
    >
      <GoogleIcon />
      Continue with Google
    </Button>
  );
}

